const assert=require('node:assert/strict');
global.window={};require('../static/date-filter.js');const D=window.DateFilter;
assert.deepEqual(D.bounds('month','2024-02'),{from:'2024-02-01',to:'2024-02-29'});
assert.deepEqual(D.bounds('year','2024'),{from:'2024-01-01',to:'2024-12-31'});
assert.deepEqual(D.bounds('quarter','2026-4'),{from:'2026-10-01',to:'2026-12-31'});
assert.deepEqual(D.bounds('year','0099'),{from:'0099-01-01',to:'0099-12-31'});
assert.ok(D.validate({from:'2026-02-30'}));
assert.ok(D.validate({from:'2026-09-02',to:'2026-09-01'}));
assert.equal(D.validate(D.bounds('year','2024'),{allowAll:false,maxDays:366}),'');
assert.ok(D.validate({from:'2024-01-01',to:'2025-01-01'},{maxDays:366}));
assert.equal(D.validate({to:'2026-09-01'}),'');
assert.ok(D.validate({to:'2026-09-01'},{allowAll:false}));
const query=new URLSearchParams('arrival_date=2026-01-01&arrival_date=__none__&department=TEST');
const dates=D.readQuery(query,'arrival_date');assert.equal(dates.values.length,2);
D.writeQuery(query,'arrival_date',{from:'2026-01-01',to:'2026-12-31',empty:'include'});
assert.equal(query.has('arrival_date'),false);assert.equal(query.get('department'),'TEST');
assert.equal(D.readQuery(query,'arrival_date').empty,'include');
D.writeQuery(query,'arrival_date',{});assert.equal([...query.keys()].length,1);
console.log('Date range, leap year, quarter, validation and query round-trip: OK');
assert.equal(D.shiftMonth('2026-12-15',1),'2027-01-01');
assert.equal(D.shiftMonth('0001-01-01',-1),'0001-01-01');
assert.equal(D.shiftMonth('9999-12-01',1),'9999-12-01');
assert.equal(D.calendarDays('2024-02-01').length,42);
assert.equal(D.calendarDays('2024-02-01')[0],'2024-01-29');
